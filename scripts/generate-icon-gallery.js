#!/usr/bin/env node
// Regenerates src/components/Icons/iconsInUse.generated.js, which the
// Storybook "Icons" page (Icons.mdx) renders as a gallery:
//   - every @mui/icons-material icon imported anywhere in src/, with the files using it
//   - every image in public/static/icons/
// Not committed (it would go stale whenever an icon is added or removed):
// .storybook/main.mjs runs this each time Storybook starts or builds.
// By hand: npm run icons:gallery

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const srcDir = path.join(root, "src");
const staticIconsDir = path.join(root, "public/static/icons");
const outFile = path.join(srcDir, "components/Icons/iconsInUse.generated.js");

function sourceFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(p);
    return /\.(js|jsx|ts|tsx)$/.test(entry.name) && p !== outFile ? [p] : [];
  });
}

// icon name -> files that import it
const muiIcons = new Map();
const use = (name, file) => {
  if (!muiIcons.has(name)) muiIcons.set(name, new Set());
  muiIcons.get(name).add(path.relative(srcDir, file));
};
for (const file of sourceFiles(srcDir)) {
  const code = fs.readFileSync(file, "utf8");
  // import Close from "@mui/icons-material/Close"
  for (const m of code.matchAll(/["']@mui\/icons-material\/([A-Za-z0-9]+)["']/g)) use(m[1], file);
  // import { Close, Check as Tick } from "@mui/icons-material"
  for (const m of code.matchAll(/import\s*\{([^}]+)\}\s*from\s*["']@mui\/icons-material["']/g)) {
    for (const part of m[1].split(",")) {
      const name = part.trim().split(/\s+as\s+/)[0];
      if (name) use(name, file);
    }
  }
}

const names = [...muiIcons.keys()].sort();
const staticIcons = fs.readdirSync(staticIconsDir).filter((f) => /\.(svg|png)$/.test(f)).sort();
// Image icons are referenced by file name; names built at runtime
// (e.g. `${level}-level-icon.png`) are not found and show as unreferenced.
const allSources = sourceFiles(srcDir).map((f) => [path.relative(srcDir, f), fs.readFileSync(f, "utf8")]);
const staticUsage = Object.fromEntries(
  staticIcons.map((f) => [f, allSources.filter(([, code]) => code.includes("/" + f) || code.includes(`"${f}"`)).map(([rel]) => rel)]),
);

const out = `// GENERATED by scripts/generate-icon-gallery.js when Storybook starts; not committed.
${names.map((n) => `import ${n} from "@mui/icons-material/${n}";`).join("\n")}

export const muiIcons = {
${names.map((n) => `  ${n},`).join("\n")}
};

// Where each icon is imported, relative to src/.
export const muiIconUsage = {
${names.map((n) => `  ${n}: ${JSON.stringify([...muiIcons.get(n)].sort())},`).join("\n")}
};

// Image file -> files that mention its name, relative to src/.
export const staticIcons = {
${staticIcons.map((f) => `  "${f}": ${JSON.stringify(staticUsage[f])},`).join("\n")}
};
`;

fs.writeFileSync(outFile, out);
console.log(`${names.length} MUI icons, ${staticIcons.length} static icons → ${path.relative(root, outFile)}`);
